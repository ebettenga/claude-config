FOLDER_NAMES = """
src source lib app apps packages pages components hooks utils helpers types typings
api server client public static assets images img icons fonts styles css
docs doc test tests __tests__ spec e2e scripts bin tools config configs
dist build out coverage node_modules vendor .git .github .vscode .claude .husky
database db migrations prisma models routes controllers services middleware
store stores context providers layouts views templates i18n locales
android ios mobile web functions workflows ci deploy docker kubernetes terraform
""".split()


def main(pkg):
    manifest = json.load(open(os.path.join(pkg, 'dist', 'material-icons.json')))
    defs = manifest['iconDefinitions']
    ext_map = {e: manifest['fileExtensions'][e] for e in EXTENSIONS if e in manifest['fileExtensions']}
    name_map = {n: manifest['fileNames'][n] for n in FILE_NAMES if n in manifest['fileNames']}
    folder_map = {}
    for n in FOLDER_NAMES:
        closed = manifest['folderNames'].get(n)
        opened = manifest['folderNamesExpanded'].get(n)
        if closed:
            folder_map[n] = [closed, opened or closed]
    wanted = set(ext_map.values()) | set(name_map.values()) | {i for pair in folder_map.values() for i in pair}
    wanted |= {manifest['file'], manifest['folder'], manifest['folderExpanded']}

    svgs = {}
    for icon in sorted(wanted):
        path = os.path.normpath(os.path.join(pkg, 'dist', defs[icon]['iconPath']))
        svg = open(path).read().strip()
        svg = re.sub(r'<\?xml[^>]*\?>', '', svg)
        svg = re.sub(r'\s+', ' ', svg).replace('> <', '><')
        if 'xmlns=' not in svg:
            svg = svg.replace('<svg', '<svg xmlns="http://www.w3.org/2000/svg"', 1)
        svgs[icon] = svg

    version = json.load(open(os.path.join(pkg, 'package.json')))['version']
    lines = [
        f'// Generated by scripts/build-icons.py from material-icon-theme {version}',
        '// (MIT, Material Extensions; see icons-LICENSE). Edit the script, not this file.',
        '',
        f'export const ICON_FILE = {json.dumps(manifest["file"])}',
        f'export const ICON_FOLDER: [string, string] = {json.dumps([manifest["folder"], manifest["folderExpanded"]])}',
        f'export const BY_EXTENSION: Record<string, string> = {json.dumps(ext_map, sort_keys=True)}',
        f'export const BY_FILE_NAME: Record<string, string> = {json.dumps(name_map, sort_keys=True)}',
        f'export const BY_FOLDER_NAME: Record<string, [string, string]> = {json.dumps(folder_map, sort_keys=True)}',
        'export const SVG: Record<string, string> = {',
    ]
    lines += [f'  {json.dumps(k)}: {json.dumps(v)},' for k, v in sorted(svgs.items())]
    lines += ['}', '']
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    open(os.path.join(here, 'hooks', 'icons.ts'), 'w').write('\n'.join(lines))
    with open(os.path.join(pkg, 'LICENSE')) as src, open(os.path.join(here, 'icons-LICENSE'), 'w') as dest:
        dest.write(f'File icons in hooks/icons.ts come from material-icon-theme {version}:\n'
                   'https://github.com/material-extensions/vscode-material-icon-theme\n\n' + src.read())
    size = sum(len(v) for v in svgs.values())
    print(f'{len(svgs)} icons, {size // 1024} KB; {len(ext_map)} extensions, {len(name_map)} file names, {len(folder_map)} folders')


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
